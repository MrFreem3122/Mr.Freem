const I18N_ATTRS = ["alt", "aria-label", "placeholder"];
const norm = (s) => s.replace(/\s+/g, " ").trim();

let currentLang = "en";
try {
  currentLang = localStorage.getItem("lang") || ((navigator.language || "").toLowerCase().startsWith("fr") ? "fr" : "en");
} catch (e) {
  /* storage unavailable: follow the browser language */
}

/* Translate a string used by scripts (form messages, button labels). */
function t(en) {
  return currentLang === "fr" && FR[en] ? FR[en] : en;
}

function swapText(value, lang) {
  const key = norm(value);
  if (!key || !FR[key]) return null;
  const lead = value.match(/^\s*/)[0];
  const trail = value.match(/\s*$/)[0];
  return lead + (lang === "fr" ? FR[key] : key) + trail;
}

/* The English original of each text node and attribute is kept, so switching back is exact. */
function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement.closest("script, style, svg, #langToggle") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.__en === undefined) node.__en = node.nodeValue;
    const next = swapText(node.__en, lang);
    if (next !== null) node.nodeValue = next;
  }

  document.querySelectorAll(I18N_ATTRS.map((a) => `[${a}]`).join(",")).forEach((el) => {
    if (el.id === "langToggle" || el.id === "themeToggle") return;
    el.__en = el.__en || {};
    I18N_ATTRS.forEach((attr) => {
      if (!el.hasAttribute(attr)) return;
      if (el.__en[attr] === undefined) el.__en[attr] = el.getAttribute(attr);
      const next = swapText(el.__en[attr], lang);
      if (next !== null) el.setAttribute(attr, next);
    });
  });

  document.querySelectorAll('meta[name="description"], meta[property="og:title"], meta[property="og:description"]').forEach((m) => {
    if (m.__en === undefined) m.__en = m.content;
    const next = swapText(m.__en, lang);
    if (next !== null) m.content = next;
  });

  if (document.__enTitle === undefined) document.__enTitle = document.title;
  document.title = swapText(document.__enTitle, lang) || document.__enTitle;

  const btn = document.getElementById("langToggle");
  if (btn) {
    const other = lang === "fr" ? "en" : "fr";
    btn.textContent = other.toUpperCase();
    btn.lang = other;
    btn.setAttribute("aria-label", other === "fr" ? "Voir le site en français" : "View the site in English");
  }

  document.documentElement.classList.remove("i18n-pending");
  document.dispatchEvent(new CustomEvent("languagechange"));
}

applyLanguage(currentLang);

document.getElementById("langToggle")?.addEventListener("click", () => {
  const next = currentLang === "fr" ? "en" : "fr";
  try {
    localStorage.setItem("lang", next);
  } catch (e) {
    /* storage unavailable: the choice lasts for this page only */
  }
  applyLanguage(next);
});
